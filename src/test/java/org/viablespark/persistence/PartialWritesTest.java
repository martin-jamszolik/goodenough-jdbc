  @Test
  void excludedStaleKeyDoesNotReplaceGeneratedIdentity() {
    BaseRepository<UpdateOnlyRecord> generated = new BaseRepository<>(jdbc) {};
    UpdateOnlyRecord entity = new UpdateOnlyRecord();
    entity.setRecordId(42L);
    entity.setNote("inserted");
    Key key = generated.save(entity).orElseThrow();
    assertFalse(key.value("record_id").equals(42L));
    assertEquals(key, entity.getRefs());
    assertEquals(42L, entity.getRecordId()); // No automatic entity refresh.
    assertEquals("inserted", generated.get(key, UpdateOnlyRecord.class).orElseThrow().getNote());
    entity.setNote("updated");
    generated.updateFields(entity, "note");
    assertEquals("updated", generated.get(key, UpdateOnlyRecord.class).orElseThrow().getNote());
    assertTrue(generated.get(Key.of("record_id", 42L), UpdateOnlyRecord.class).isEmpty());
    SchemaValidator.assertMappings(database, UpdateOnlyRecord.class);
  }

  @Test
  void excludedStaleCompositePartIsReplacedWhileInsertOnlyAssignedPartIsPreserved() {
    jdbc.execute(
        "CREATE TABLE composite_record (tenant_id BIGINT,"
            + " record_id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100),"
            + " display_name VARCHAR(100), PRIMARY KEY (tenant_id, record_id))");
    BaseRepository<GeneratedCompositeRecord> composite = new BaseRepository<>(jdbc) {};
    GeneratedCompositeRecord entity = new GeneratedCompositeRecord();
    entity.setTenantId(7L);
    entity.setRecordId(42L);
    entity.setName("inserted");
    Key key = composite.save(entity).orElseThrow();
    assertEquals(7L, key.value("tenant_id"));
    assertEquals(100L, key.value("record_id"));
    assertEquals(key, entity.getRefs());
    assertEquals(
        "inserted", composite.get(key, GeneratedCompositeRecord.class).orElseThrow().getName());
    entity.setName("updated");
    composite.save(entity);
    assertEquals(
        "updated", composite.get(key, GeneratedCompositeRecord.class).orElseThrow().getName());
    assertTrue(
        composite
            .get(Key.of("tenant_id", 7L).add("record_id", 42L), GeneratedCompositeRecord.class)
            .isEmpty());
    SchemaValidator.assertMappings(database, GeneratedCompositeRecord.class);
  }

  @Test
  void excludedStaleKeyIsNotFallbackIdentityWhenDriverReturnsNoGeneratedKeys() {
    JdbcTemplate untouched = mock(JdbcTemplate.class);
    BaseRepository<UpdateOnlyRecord> generated =
        new BaseRepository<>(untouched) {
          @Override
          protected KeyHolder execWithKey(String sql, Object... args) {
            return new GeneratedKeyHolder();
          }
        };
    UpdateOnlyRecord entity = new UpdateOnlyRecord();
    entity.setRecordId(42L);
    assertTrue(generated.save(entity).isEmpty());
    assertTrue(entity.isNew());
    verifyNoInteractions(untouched);
  }

