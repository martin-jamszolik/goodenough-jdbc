  private static Record record(String name, String note) {
    Record entity = new Record();
    entity.setName(name);
    entity.setNote(note);
    return entity;
  }

  private static Parent parent(long id) {
    Parent parent = new Parent();
    parent.setRefs(Key.of("parent_id", id));
    return parent;
  }

  @Named("write_record")
  @PrimaryKey("record_id")
  public static class Record extends NameSlice {
    private Long recordId;
    private String note;
    @Ref private Parent parent;

    @Ref(value = "lookup_id", label = "label")
    private RefValue lookup;

    @Write(insertable = false, updatable = false)
    private String createdValue;

    @Write(updatable = false)
    private String origin;

    @Skip private String ignored;

    public Long getRecordId() {
      return recordId;
    }

    public void setRecordId(Long value) {
      recordId = value;
    }

    public String getNote() {
      return note;
    }

    public void setNote(String value) {
      note = value;
    }

    public Parent getParent() {
      return parent;
    }

    public void setParent(Parent value) {
      parent = value;
    }

    public RefValue getLookup() {
      return lookup;
    }

    public void setLookup(RefValue value) {
      lookup = value;
    }

    public String getCreatedValue() {
      return createdValue;
    }

    public void setCreatedValue(String value) {
      createdValue = value;
    }

    public String getOrigin() {
      return origin;
    }

    public void setOrigin(String value) {
      origin = value;
    }

    public String getIgnored() {
      return ignored;
    }

    public void setIgnored(String value) {
      ignored = value;
    }

    public List<Record> getChildren() {
      return List.of();
    }
  }

